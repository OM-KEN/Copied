// Manual QA only; the self-test uses a named pasteboard.
import AppKit
import Darwin

private let scenarios: [(key: String, title: String, marker: String?, expected: String)] = [
    ("ordinary", "普通复制", nil, "按现有设置显示普通文本和声音，用作对照。"),
    ("concealed", "Concealed", "org.nspasteboard.ConcealedType",
     "默认模式仅显示“已复制（内容已隐藏）”；仅提醒沿用所选样式。无正文、来源、Action或本次重现；声音最多一次。轻打扰分类筛选下可能仅有声音。"),
    ("transient", "Transient", "org.nspasteboard.TransientType", "不弹窗、不响，本次内容不能重现。"),
    ("auto-generated", "AutoGenerated", "org.nspasteboard.AutoGeneratedType", "不弹窗、不响，本次内容不能重现。"),
]
private let syntheticText = "Copied privacy QA: synthetic text"
private let warning = "每次选择会替换当前剪贴板为固定合成文本，不读取、备份或恢复旧内容；退出不清空。请保持Copied运行，并允许当前终端来源。"

private func help() {
    print("双击verify-clipboard-privacy.command，按1–4测试，q退出。")
    print("一次性调用：verify-clipboard-privacy.command ordinary|concealed|transient|auto-generated")
    print("--self-test仅用命名临时剪贴板；--help显示帮助。非交互无参数不写入。")
    print(warning)
}

private func write(_ index: Int, to board: NSPasteboard) -> Bool {
    let item = NSPasteboardItem()
    guard item.setString(syntheticText, forType: .string) else { return false }
    if let marker = scenarios[index].marker, !item.setData(Data(), forType: .init(marker)) { return false }
    board.clearContents()
    return board.writeObjects([item])
}

private func select(_ input: String) -> Int? {
    let value = input.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
    return scenarios.indices.first { value == String($0 + 1) || value == scenarios[$0].key }
}

private func selfTest() {
    let board = NSPasteboard.withUniqueName()
    defer { board.releaseGlobally() }
    let markers = Set(scenarios.compactMap(\.marker).map { NSPasteboard.PasteboardType($0) })
    for index in scenarios.indices {
        precondition(select(String(index + 1)) == index && select(scenarios[index].key) == index)
        precondition(write(index, to: board))
        let items = board.pasteboardItems ?? []
        precondition(items.count == 1 && items[0].string(forType: .string) == syntheticText)
        let expected = Set(scenarios[index].marker.map { [NSPasteboard.PasteboardType($0)] } ?? [])
        precondition(Set(board.types ?? []).intersection(markers) == expected)
    }
    print("四种情景自测通过；只访问命名临时剪贴板，未访问系统剪贴板。")
}

private let arguments = Array(CommandLine.arguments.dropFirst())
if arguments == ["--self-test"] { selfTest(); exit(0) }
if arguments == ["--help"] || arguments == ["-h"] { help(); exit(0) }
if arguments.count == 1, let index = select(arguments[0]) {
    print(warning)
    guard write(index, to: .general) else { fputs("测试写入失败。\n", stderr); exit(1) }
    print("已写入：\(scenarios[index].title)；预期：\(scenarios[index].expected)")
    exit(0)
}
if !arguments.isEmpty { help(); fputs("无效选项，未写入剪贴板。\n", stderr); exit(1) }
if isatty(STDIN_FILENO) == 0 { help(); exit(0) }
print(warning)
while true {
    for index in scenarios.indices { print("\(index + 1). \(scenarios[index].title)") }
    print("选择后立即替换剪贴板；q退出：", terminator: " ")
    fflush(stdout)
    guard let input = readLine() else { break }
    if input.trimmingCharacters(in: .whitespacesAndNewlines).lowercased() == "q" { break }
    guard let index = select(input) else { print("请输入1–4或q，未写入剪贴板。"); continue }
    guard write(index, to: .general) else { fputs("测试写入失败。\n", stderr); exit(1) }
    print("预期：\(scenarios[index].expected)")
}
